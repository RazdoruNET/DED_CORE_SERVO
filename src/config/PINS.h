#ifndef CONFIG_PINS_H
#define CONFIG_PINS_H

#include <Arduino.h>

// Распиновка модуля. Пины совпадают с заводской платой DED SERVO DRIVER,
// чтобы новая прошивка встала на готовое железо без перепайки.

// H-мост: 16 = «вверх», 17 = «вниз». Оба HIGH — тормоз (двигатель замкнут),
// оба LOW — выбег. Направление соответствует заводской прошивке, поэтому
// название пина значит сторону привода, а не знак разницы положения.
constexpr uint8_t PIN_MOTOR_UP = 16;
constexpr uint8_t PIN_MOTOR_DOWN = 17;

// Разрешение драйвера моста: HIGH — драйвер включён.
constexpr uint8_t PIN_DRIVER_ENABLE = 32;

// Датчик положения — аналоговый выход, ADC1 (GPIO35).
constexpr uint8_t PIN_POSITION = 35;

// Свободный вход заводской платы. В контуре не участвует, но остаётся входом:
// к нему может быть подключён концевик или перемычка версии платы.
constexpr uint8_t PIN_SPARE_INPUT = 34;

#endif // CONFIG_PINS_H
